"""Regenerate src/runner_protocol/schema_models.py from catalog/schema/*.json.

Usage (from runners/_protocol/):  uv run python tools/generate_schema_models.py

The Zod 4 source of truth is packages/schema/src/protocol.ts; `bun run gen`
writes catalog/schema/*.json. This script combines the three wire-contract
schemas (runner-info, track-request, track-response) into one $defs document
and runs datamodel-codegen (draft-2020-12) over it.

Documented codegen adjustments (kept minimal, applied deterministically):
1. `required` entries whose property has a JSON `default` are stripped before
   codegen. datamodel-codegen drops defaults on required fields, but the Zod
   source (`.default("v1")`, `.default([])`) means optional-on-input — so the
   default must survive. Today this affects `RunnerInfo.protocol` and
   `RunnerInfo.host.gpus`.
2. Titles are injected for the nested (title-less) object models so class
   names are deterministic (codegen names them by collision order otherwise,
   e.g. "Model1"). ServedModel, Host, Gpu, TrackItem, TrackResult.
3. The spurious root `class Model(RootModel[Any])` that codegen emits for a
   bare $defs document is removed, and the RootModel import pruned if unused.
4. `usage` (`anyOf: [{}, null]`) collapses to `Any` — equivalent to the Zod
   `z.unknown().nullable()` since Any already accepts null.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
REPO_ROOT = PROJECT.parent.parent
SCHEMA_DIR = REPO_ROOT / "catalog" / "schema"
OUTPUT = PROJECT / "src" / "runner_protocol" / "schema_models.py"

CONTRACT = [("runner-info.json", "RunnerInfo"), ("track-request.json", "TrackRequest"), ("track-response.json", "TrackResponse")]

# JSON-pointer-style paths (tuples) inside each def that get a stable title.
TITLE_PATHS: dict[str, dict[tuple[str, ...], str]] = {
    "RunnerInfo": {
        ("properties", "models", "items"): "ServedModel",
        ("properties", "host"): "Host",
        ("properties", "host", "properties", "gpus", "items"): "Gpu",
    },
    "TrackRequest": {("properties", "items", "items"): "TrackItem"},
    "TrackResponse": {("properties", "results", "items"): "TrackResult"},
}

HEADER = '''"""Pydantic models for the runner wire contract: GET /info, POST /v1/<track>.

GENERATED by tools/generate_schema_models.py from catalog/schema/
(runner-info.json, track-request.json, track-response.json). Zod 4 source of
truth: packages/schema/src/protocol.ts. DO NOT EDIT BY HAND — regenerate with
`uv run python tools/generate_schema_models.py` (dev dependency of this
project) and commit the result.

Generator adjustments over raw codegen output (see the script's docstring):
required entries carrying a JSON default are stripped so the default survives
(Zod `.default()` = optional-on-input), nested models get stable titles, and
the spurious root RootModel[Any] is removed.
"""
'''


def strip_defaulted_required(node: Any) -> None:
    """Remove `required` entries whose property declares a `default`, recursively."""
    if isinstance(node, dict):
        props = node.get("properties")
        required = node.get("required")
        if isinstance(props, dict) and isinstance(required, list):
            kept = [r for r in required if not (r in props and isinstance(props[r], dict) and "default" in props[r])]
            if kept != required:
                print(f"  stripped defaulted-required: {sorted(set(required) - set(kept))}")
                if kept:
                    node["required"] = kept
                else:
                    del node["required"]
        for value in node.values():
            strip_defaulted_required(value)
    elif isinstance(node, list):
        for value in node:
            strip_defaulted_required(value)


def inject_titles(key: str, schema: dict[str, Any]) -> None:
    for path, title in TITLE_PATHS.get(key, {}).items():
        node: Any = schema
        for part in path:
            node = node[part]
        node["title"] = title


def strip_root_models(text: str) -> str:
    """Remove the spurious `class X(RootModel[Any])` codegen emits for the bare doc root."""
    cleaned, count = re.subn(r"class \w+\(RootModel\[Any\]\):\n    root: Any\n\n\n", "", text)
    if count:
        print(f"  removed {count} spurious RootModel block(s)")
    if not re.search(r"RootModel\[", cleaned):
        cleaned = re.sub(r"^from pydantic import (.*\bRootModel\b.*)$", lambda m: _prune_import(m.group(1)), cleaned, flags=re.MULTILINE)
    return cleaned


def _prune_import(names: str) -> str:
    kept = ", ".join(n.strip() for n in names.split(",") if n.strip() != "RootModel")
    return f"from pydantic import {kept}"


def main() -> None:
    defs: dict[str, Any] = {}
    for filename, key in CONTRACT:
        schema = json.loads((SCHEMA_DIR / filename).read_text(encoding="utf-8"))
        print(f"{key}:")
        strip_defaulted_required(schema)
        inject_titles(key, schema)
        defs[key] = schema

    combined = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}

    with tempfile.TemporaryDirectory() as tmp:
        input_path = Path(tmp) / "combined.json"
        input_path.write_text(json.dumps(combined), encoding="utf-8")
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(input_path),
                "--input-file-type",
                "jsonschema",
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--use-title-as-name",
                "--preset",
                "standard-py313-20261017",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
        if result.stderr.strip():
            print(result.stderr, file=sys.stderr)

    body = strip_root_models(result.stdout)
    OUTPUT.write_text(HEADER + "\n" + body, encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
